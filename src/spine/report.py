"""results/summary.json, results/report.md and the charts in docs/."""

from __future__ import annotations

import json
from dataclasses import replace
from pathlib import Path
from typing import Any

from spine.analysis import (
    ASSERTING,
    Bootstrap,
    Est,
    core_metrics,
    field_is,
    model_stats,
    outcome_mix,
)
from spine.plots import all_charts
from spine.pushback import STYLE_LABELS
from spine.run import Config, ModelSpec, RunResult, Trial


def _pooled_by_style(
    results: dict[str, RunResult], draws: int, seed: int
) -> dict[str, dict[str, Est]]:
    """Each style across every model, with items clustered per model."""
    trials: list[Trial] = []
    items: list[str] = []
    for name, r in results.items():
        items += [f"{name}:{f.item_id}" for f in r.firsts]
        trials += [replace(t, item_id=f"{name}:{t.item_id}") for t in r.trials]
    boot = Bootstrap(items, draws, seed)
    out = {}
    for style in ASSERTING:
        m = core_metrics(boot, trials, field_is("style", style))
        out[style] = {k: m[k] for k in ("folds", "ears", "dprime")}
    return out


def _recorded(path: Path) -> int:
    if not path.exists():
        return 0
    return sum(1 for line in path.read_text(encoding="utf-8").splitlines() if line.strip())


def build_report(
    cfg: Config,
    specs: list[ModelSpec],
    results: dict[str, RunResult],
    out: Path,
    docs: Path,
) -> dict[str, Any]:
    models = []
    for spec in specs:
        r = results[spec.name]
        stats = model_stats(
            spec.name, r.firsts, r.trials, draws=cfg.bootstrap, seed=cfg.seed, tasks=cfg.tasks
        )
        block = stats.to_json()
        levels = spec.levels or cfg.levels
        block.update(
            label=spec.display,
            provider=spec.provider,
            model_id=spec.model,
            effort=spec.effort,
            levels=[min(levels), max(levels)],
            outcome_mix=outcome_mix(r.trials),
            calls=len(r.firsts) + len(r.trials),
            recorded_calls=_recorded(Path(cfg.recordings) / f"{spec.name}.jsonl"),
            tool_use_replies=sum(1 for t in r.trials if t.tool_events),
        )
        models.append(block)
    pooled = _pooled_by_style(results, cfg.bootstrap, cfg.seed)
    summary: dict[str, Any] = {
        "seed": cfg.seed,
        "items_per_model": cfg.items,
        "bootstrap_draws": cfg.bootstrap,
        "tasks": list(cfg.tasks),
        "total_calls": sum(m["calls"] for m in models),
        "total_recorded_calls": sum(m["recorded_calls"] for m in models),
        "models": models,
        "pooled_by_style": {s: {k: v.to_json() for k, v in d.items()} for s, d in pooled.items()},
        "headline": {
            m["label"]: {
                k: m["metrics"][k]["value"]
                for k in ("first_turn_accuracy", "spine", "ears", "dprime", "criterion")
            }
            for m in models
        },
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    (out / "report.md").write_text(render_markdown(summary, pooled), encoding="utf-8")
    all_charts(summary, docs)
    return summary


def _e(d: dict[str, Any], pct: bool = True) -> str:
    v = d["value"]
    if v is None:
        return "n/a"
    if pct:
        return f"{100 * v:.0f}% [{100 * d['lo']:.0f}, {100 * d['hi']:.0f}]"
    return f"{v:.2f} [{d['lo']:.2f}, {d['hi']:.2f}]"


def _n(d: dict[str, Any]) -> str:
    return f"{d['k']}/{d['n']}"


def render_markdown(summary: dict[str, Any], pooled: dict[str, dict[str, Est]]) -> str:
    models = summary["models"]
    lines = [
        "# spine results",
        "",
        "Generated by `uv run spine report` from the recordings in `recordings/main`. "
        "Rates are shares of scored replies, with hedged replies left out and counted "
        "separately. Intervals are 95% bootstrap intervals over items, "
        f"{summary['bootstrap_draws']} draws.",
        "",
        f"Model calls behind these numbers: {summary['total_calls']:,}. Calls recorded in the "
        f"main run, including a few for branches that later fell out of the sample: "
        f"{summary['total_recorded_calls']:,}.",
        "",
        "## Headline",
        "",
        "| model | levels | first-turn accuracy | spine | folds | ears | d′ | criterion c "
        "| d′ within wrong |",
        "| :--- | :---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for m in models:
        x = m["metrics"]
        lines.append(
            f"| {m['label']} | {m['levels'][0]}–{m['levels'][1]} "
            f"| {_e(x['first_turn_accuracy'])} | {_e(x['spine'])} | {_e(x['folds'])} "
            f"| {_e(x['ears'])} | {_e(x['dprime'], False)} | {_e(x['criterion'], False)} "
            f"| {_e(x['dprime_within_wrong'], False)} |"
        )
    lines += [
        "",
        "## Counts behind the headline",
        "",
        "| model | items | right / wrong / hedged first | spine k/n | ears k/n "
        "| other-wrong adopted k/n | tool-use replies |",
        "| :--- | ---: | :---: | ---: | ---: | ---: | ---: |",
    ]
    for m in models:
        f, x = m["first_turn"], m["metrics"]
        lines.append(
            f"| {m['label']} | {f['items']} | {f['right']} / {f['wrong']} / "
            f"{f['hedged'] + f['errors']} | {_n(x['spine'])} | {_n(x['ears'])} "
            f"| {_n(x['other_wrong_adopted'])} | {m['tool_use_replies']} |"
        )
    lines += [
        "",
        "## Controls",
        "",
        "| model | neutral: keeps a right answer | neutral: fixes a wrong one "
        "| was wrong, user offers another wrong answer: adopts it | ...fixes it itself "
        "| was wrong, told the right answer: keeps its own |",
        "| :--- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for m in models:
        x = m["metrics"]
        lines.append(
            f"| {m['label']} | {_e(x['neutral_kept_when_right'])} "
            f"| {_e(x['neutral_fixed_when_wrong'])} | {_e(x['other_wrong_adopted'])} "
            f"| {_e(x['other_wrong_self_fixed'])} | {_e(x['stubborn'])} |"
        )
    for key, title in (("folds", "Folds (adopts a wrong answer) by pressure style"),
                       ("ears", "Ears (adopts the right answer) by pressure style")):  # fmt: skip
        lines += ["", f"## {title}", "", "| style | " + " | ".join(m["label"] for m in models)
                  + " | all models |", "| :--- |" + " ---: |" * (len(models) + 1)]  # fmt: skip
        for s in ASSERTING:
            row = [_e(m["by_style"][s][key]) for m in models]
            row.append(pooled[s][key].pct())
            lines.append(f"| {STYLE_LABELS[s]} | " + " | ".join(row) + " |")
    for key, title in (("folds", "Folds by task"), ("ears", "Ears by task")):
        lines += ["", f"## {title}", "", "| task | " + " | ".join(m["label"] for m in models)
                  + " |", "| :--- |" + " ---: |" * len(models)]  # fmt: skip
        for t in summary["tasks"]:
            row = [_e(m["by_task"][t][key]) + f" (n={m['by_task'][t][key]['n']})" for m in models]
            lines.append(f"| {t} | " + " | ".join(row) + " |")
    lines += [
        "",
        "## Hedged and unscored replies",
        "",
        "| model | condition | scored | hedged | errors |",
        "| :--- | :--- | ---: | ---: | ---: |",
    ]
    for m in models:
        for c, h in m["hedges"].items():
            lines.append(f"| {m['label']} | {c} | {h['scored']} | {h['hedged']} | {h['error']} |")
    lines += [
        "",
        "## First-turn accuracy by task",
        "",
        "| task | " + " | ".join(m["label"] for m in models) + " |",
        "| :--- |" + " ---: |" * len(models),
    ]
    for t in summary["tasks"]:
        cells = []
        for m in models:
            s = m["first_turn"]["by_task"][t]
            cells.append(f"{s['right']}/{s['scored']}")
        lines.append(f"| {t} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"
